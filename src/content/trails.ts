// • Cada MATÉRIA da biblioteca é uma trilha por si só: os tópicos estão na
//   ordem recomendada de estudo (do básico ao avançado).
// • Cada CARREIRA reúne matérias com um peso (concursos: nº de questões do
//   último edital; tecnologia: importância relativa no mercado), usado para
//   montar o ciclo de estudos.
//
// Fontes consultadas em 21/10/2026 (ver `sources` de cada carreira). Editais
// mudam: confira sempre o edital vigente quando for publicado.

export type TopicTree = Array<string | [string, TopicTree]>

export interface Reference {
  title: string
  url: string
}

export interface SubjectDef {
  key: string
  name: string
  area: 'Concursos' | 'Tecnologia' | 'Idiomas'
  color: string
  icon: string
  difficulty: 1 | 2 | 3 | 4 | 5
  description: string
  topics: TopicTree
  references?: Reference[]
}

export interface CareerTrail {
  key: string
  name: string
  area: 'Concursos' | 'Tecnologia'
  icon: string
  summary: string
  basis: string
  exam?: string
  /** Peso de cada matéria (concursos: nº de questões/itens; tecnologia: relevância). */
  subjects: Array<{ key: string; weight: number; note?: string }>
  sources: Reference[]
  tips: string[]
}

